"""
RunSimulationModel(title, SELECTEDYEARS, Capacity_r, TransmissionCapacity_r, problem, input, time_series_data)

Run deterministic simulations across `SELECTEDYEARS` using fixed capacities. Returns averages and a table for reporting.
Only used when `problem.simulate_results = true`.
"""
function RunSimulationModel(title, SELECTEDYEARS, Capacity_r, TransmissionCapacity_r, problem, input, time_series_data)
    @unpack demand_response_penalty, VOLL, time_step = problem
    @unpack simulated_load = time_series_data
    result = []
    
    # Initialize accumulators for Jain's Index data
    AccumulatedENS = Dict(r => 0.0 for r in input.REGION)
    AccumulatedDemandResponse = Dict(r => 0.0 for r in input.REGION)
    AccumulatedDemand = Dict(r => 0.0 for r in input.REGION)

    for s in SELECTEDYEARS
        TotalLoad_r = 8760 /(time_step * input.no_periods) * sum(simulated_load[s,:,:]) * time_step
        simulation_data = prepare_simulation_data(problem, input, time_series_data, s)
                                                  
        model = Build_Simulation_Model(Capacity_r, TransmissionCapacity_r, problem, input, simulation_data)
        @unpack m, Electricity, TotalEmissions, OperationalCost, FixedCost, InvestmentCost, TotalDemandResponseCost, TotalENSCost, TotalENS_per_region, TotalDemand_per_region, TotalDemandResponse_per_region = model
        println("\nSolving simulation model (pair $(s+1978)-$(s+1979))...")
        optimize!(m)

        # Collect simulation results
        ObjVal_r = objective_value(m) / 1e6
        TotalCosts_r = (value.(InvestmentCost) + value.(OperationalCost) + value.(FixedCost) + value.(TotalDemandResponseCost) + value.(TotalENSCost) ) /1e6
        TotalCostsWithoutENS_r = (value.(InvestmentCost) + value.(OperationalCost) + value.(FixedCost) + value.(TotalDemandResponseCost)) / 1e6 
        InvestmentCost_r = value.(InvestmentCost) / 1e6
        OperationalCost_r = value.(OperationalCost) / 1e6
        FixedCost_r = value.(FixedCost) / 1e6
        TotalEmissions_r = value.(TotalEmissions) / 1e6
        TotalDemandResponseCost_r = value.(TotalDemandResponseCost) / 1e6
        TotalENSCost_r = value.(TotalENSCost) / 1e6
        DemandResponse_r = value.(TotalDemandResponseCost) / demand_response_penalty / 1e6 
        ENS_r = value.(TotalENSCost) / VOLL / 1e6 
        SatisfiedLoad_r = (TotalLoad_r - value.(TotalDemandResponseCost) / demand_response_penalty - value.(TotalENSCost) / VOLL ) / 1e6
        UnitSystemCost_r = TotalCosts_r / SatisfiedLoad_r
      
        # Accumulate per-region results for Jain's Index
        for r in input.REGION
            AccumulatedENS[r] += value(TotalENS_per_region[r])
            AccumulatedDemandResponse[r] += value(TotalDemandResponse_per_region[r])
            AccumulatedDemand[r] += value(TotalDemand_per_region[r])
        end

        # Append results to the result array
        push!(result, (ObjVal_r, TotalCosts_r, TotalCostsWithoutENS_r, InvestmentCost_r, FixedCost_r, OperationalCost_r, TotalEmissions_r, TotalDemandResponseCost_r, TotalENSCost_r, SatisfiedLoad_r, DemandResponse_r, ENS_r, UnitSystemCost_r)) 
        
        # Reset the model (optional, depending on your use case)
        m = nothing
    end
    
    # Convert the result array to a DataFrame
    df = DataFrame(result)
    
    # Convert the DataFrame to a NamedArray
    named_array = NamedArray(Matrix(df), (1:size(df, 1), names(df)))

    # Calculate the averages for each column
    averages = mean(named_array, dims=1)  # Compute mean along the first dimension (rows)
    averages = vec(averages)  # Flatten into a 1D vector for easier access

    # Create a named tuple for averages
    AverageObjVal = averages[1]
    AverageCosts = averages[2]
    AverageTotalCostsWithoutENS = averages[3]
    AverageInvestmentCost = averages[4]
    AverageFixedCost = averages[5]
    AverageOperationalCost = averages[6]
    AverageTotalEmissions = averages[7]
    AverageTotalDemandResponseCost = averages[8]
    AverageTotalENSCost = averages[9]
    AverageSatisfiedLoad = averages[10]
    AverageDemandResponse = averages[11]
    AverageENS = averages[12]
    # Average unit system cost = average total costs / average satisfied load (ratio of averages, not average of ratios)
    averages[13] = averages[2] / averages[10]
    AverageUnitSystemCost = averages[13]
    
    # Add the averages row as the first row (so it becomes first column after transpose)
    extended_array = vcat(reshape(averages, 1, :), named_array)  # Prepend averages as first row
    
    # Update the row names to include "Average" as the first row
    new_row_names = vcat(["Average"], 1:size(df, 1))
    extended_named_array = NamedArray(extended_array, (new_row_names, names(df)))

    # Transpose to get final table layout (averages is now first column)
    transposed_array = extended_named_array'
    
    # Prepare column headers with "Average" first
    column_headers = vcat("Average", ["$(y+1978)-$(y+1979)" for y in SELECTEDYEARS])

    # Prepare the table for saving
    table = [(
        title, 
        transposed_array,
        column_headers,
        ["Objective value",
        "Total costs (M€)",
        "Total costs without energy not served (M€)",
        "Investment cost (M€)",
        "Fixed cost (M€)",
        "Operational cost (M€)",
        "CO2 emissions (Mt)",
        "Demand Response cost (M€)",
        "ENS cost (M€)",
        "Satisfied load (TWh)",
        "Demand Response (TWh)",
        "Energy not served (TWh)",
        "Unit system cost (€/MWh)"]
    )]

    # Calculate averages for Jain's Index
    num_sims = length(SELECTEDYEARS)
    AverageENS_per_region = AxisArray([AccumulatedENS[r] / num_sims for r in input.REGION], input.REGION)
    AverageDemandResponse_per_region = AxisArray([AccumulatedDemandResponse[r] / num_sims for r in input.REGION], input.REGION)
    AverageDemand_per_region = AxisArray([AccumulatedDemand[r] / num_sims for r in input.REGION], input.REGION)
    
    # Return the named tuple of averages and the table
    return (; AverageObjVal, 
    AverageCosts, 
    AverageTotalCostsWithoutENS, 
    AverageInvestmentCost, 
    AverageFixedCost, 
    AverageOperationalCost, 
    AverageTotalEmissions, 
    AverageTotalDemandResponseCost, 
    AverageTotalENSCost, 
    AverageSatisfiedLoad, 
    AverageDemandResponse, 
    AverageENS, 
    AverageUnitSystemCost, 
    table,
    AverageENS_per_region,
    AverageDemand_per_region,
    AverageDemandResponse_per_region)
end

