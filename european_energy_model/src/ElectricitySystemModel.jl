"""
SolveStochasticModel(problem, input, scenario_data, time_series_data)

High-level wrapper that:
1. Solves the stochastic optimization model
2. Processes results into summary tables (via `GetTableSummary`)
3. Optionally runs deterministic simulations and appends simulation tables
Returns a named tuple with `tables` and the raw `solution` results.
"""
function SolveStochasticModel(problem, input, scenario_data, time_series_data)
    # Here we solve a model based on scenario data
    tables = []
    solve_time = @elapsed solution = RunStochasticModel(problem, input, scenario_data)
    @unpack Capacity_r, TransmissionCapacity_r = solution
    solution_summary = GetTableSummary(problem, input, scenario_data, solution)
    #PlotSolution(solution_summary, problem, input, scenario_data)
    append!(tables, solution_summary.tables)
    SELECTEDYEARS = time_series_data.SIMULATION_YEARS
    simulation_results = nothing
    simulation_time = 0.0
    if problem.simulate_results
        sim_t0 = time_ns()
        simulation_output = RunSimulationModel("Simulation Results:", SELECTEDYEARS, Capacity_r, TransmissionCapacity_r, problem, input, time_series_data)
        
        # Calculate Jain's Index and create summary table
        @unpack AverageENS_per_region, AverageDemand_per_region, AverageDemandResponse_per_region = simulation_output
        loss_ratios = Float64[]
        for r in input.REGION
            dem = AverageDemand_per_region[r]       # MWh 
            eens = AverageENS_per_region[r]    # MWh 

            if dem > 0
                # Calculate the ratio of LOST energy (e.g., 0.005 for 5%)
                ratio = eens / dem
                push!(loss_ratios, ratio)
            else
                # If no demand, there is no "loss ratio", push 0.0 (perfect)
                push!(loss_ratios, 0.0)
            end
        end

        n = length(loss_ratios)
        sum_x = sum(loss_ratios)
        sum_sq_x = sum(loss_ratios.^2)

        # If the system is PERFECT (all zeros), Jain's Index is undefined (0/0).
        if sum_sq_x == 0
            # Case: No unserved energy anywhere.
            # The system is perfectly fair (everyone has 0 loss).
            jains_index = 1.0 
            println("System is perfectly robust (0 energy not served).")
        else
            # Case: Some losses exist. Calculate fairness of the LOSS distribution.
            jains_index = (sum_x^2) / (n * sum_sq_x)
        end

        jains_df = DataFrame(Metric = ["Average Energy Not Served (GWh)", "Jain's Fairness Index"], Value = [@sprintf("%.4f", sum(AverageENS_per_region)/1000), @sprintf("%.4f", jains_index)])
        push!(tables, ("Fairness Analysis:", jains_df, ["Metric", "Value"], []))

        regional_df = DataFrame(
            "Region" => string.(input.REGION), 
            "Average Energy Not Served (GWh)" => [AverageENS_per_region[r]/1000 for r in input.REGION], 
            "Average Demand Response (GWh)" => [AverageDemandResponse_per_region[r]/1000 for r in input.REGION],
            "Average Demand (GWh)" => [AverageDemand_per_region[r]/1000 for r in input.REGION]
        )
        push!(tables, ("Regional Data:", regional_df, names(regional_df), []))

        append!(tables, simulation_output.table)
        simulation_results = simulation_output
        simulation_time = (time_ns() - sim_t0) / 1e9
    end
    return (; tables, solution, simulation_results, solve_time, simulation_time)
end