"""
Build_Simulation_Model(Capacity_r, TransmissionCapacity_r, problem, input, simulation_data)

Construct a deterministic simulation model using fixed capacities from the stochastic solution.
Used only when `problem.simulate_results = true`.
- `Capacity_r`, `TransmissionCapacity_r` come from the solved stochastic model
- `simulation_data` contains time-series for a single historical year
Returns the model and variables needed to collect simulation outputs (Electricity, TotalEmissions, costs, etc.).
"""
function Build_Simulation_Model(Capacity_r, TransmissionCapacity_r, problem, input, simulation_data)
    println("\nBuilding models...")
    @unpack REGION, PLANT, TECH, PERIOD, no_periods, no_regions, no_plants, no_techs, inv_cost, fixed_cost, var_cost, fuel_cost, eta,
    emissionfactor, crf, maxcap, hydroreservoir, PSopenReservoir, PSclosedReservoir, min_reservoir_level, transmissioncost, distance, valid_links, loss_per_K_Km, crf_t = input 
    @unpack cf, load, res_inflow, ror_inflow, PS_inflow = simulation_data
    @unpack carbon_cap, time_step, demand_response_penalty, VOLL, demand_response_ratio, planned_outage_rate = problem

    m = Model(Gurobi.Optimizer)
    set_optimizer_attributes(m, "Threads" => 0, "Method"=> 2, "Crossover"=> 0)

    @variables m begin
        OperationalCost                                           >= 0        # €
        FixedCost                                                 >= 0        # €
        TotalDemandResponseCost                                      >= 0        # €
        TotalENSCost                                         >= 0        # €
        TotalEmissions                                            >= 0        # ton CO2
        InvestmentCost                                            >= 0        # €
        Electricity[r in REGION, p in TECH, h in PERIOD]          >= 0        # MWh/h
        DemandResponse[r in REGION, h in PERIOD]                     >= 0        # MWh/h
        ChargeLevel[r in REGION, h in PERIOD]                     >= 0        # MWh
        ReservoirLevel[r in REGION, h in PERIOD]                  >= 0        # MWh
        PSopenLevel[r in REGION, h in PERIOD]                     >= 0        # MWh
        PSclosedLevel[r in REGION, h in PERIOD]                   >= 0        # MWh   
        H2StorageLevel[r in REGION, h in PERIOD]                  >= 0        # MWh
        Transmission[r in REGION, r1 in REGION, h in PERIOD; valid_links[r, r1]]       >= 0        # MWh/h
        PlannedOutage[r in REGION, h in PERIOD]                   >= 0        # MW 
        ENS[r in REGION, h in PERIOD]                        >= 0        # MW
    end     #variables
    
    @constraints m begin
        # ELECTRICITY GENERATION
        Generation_0[r in REGION, p in PLANT, h in PERIOD; p != :Nuclear],
            Electricity[r, p, h] <= Capacity_r[r, p] * cf[r, p, h] * time_step

        Generation_1[r in REGION, h in PERIOD],
            Electricity[r, :Nuclear, h] <= Capacity_r[r, :Nuclear] * time_step - PlannedOutage[r, h]

        # BATTERIES & INVERTER
        InverterCapacity[r in REGION, h in PERIOD], 
            Electricity[r, :Inverter, h]  + Electricity[r, :Battery, h] <= Capacity_r[r, :Inverter] * time_step
        
        StorageSize[r in REGION, h in PERIOD],
            ChargeLevel[r, h] <= Capacity_r[r, :Battery]

        ElecStorageBalance[r in REGION, h in PERIOD],
            ChargeLevel[r, h] == ChargeLevel[r, h>1 ? h-1 : length(PERIOD)] + eta[:Battery] * Electricity[r, :Battery, h]  +
                - Electricity[r, :Inverter, h]/eta[:Inverter]

        # ELECTRICITY TRANSMISSION
        ElecTransmission[r in REGION, r1 in REGION, h in PERIOD; r1 > r && valid_links[r, r1]],
        	Transmission[r, r1, h] + Transmission[r1, r, h] <= TransmissionCapacity_r[r, r1] * time_step

        # NUCLEAR
        Outage_Planned[r in REGION],
            sum(PlannedOutage[r, h] for h in PERIOD) == planned_outage_rate * no_periods * Capacity_r[r, :Nuclear] * time_step; 

        # HYDROPOWER RESERVOIR
        ReservoirBalance[r in REGION, h in PERIOD],
            ReservoirLevel[r, h] <= ReservoirLevel[r, h>1 ? h-1 : length(PERIOD)] + res_inflow[r, h] * time_step +
            - Electricity[r, :HydroRes, h]

        ReservoirSize[r in REGION, h in PERIOD],
            ReservoirLevel[r, h] <= hydroreservoir[r] * 1e6

        MinReservoirLevel[r in REGION, h in PERIOD],
            ReservoirLevel[r, h] >= min_reservoir_level[r] * hydroreservoir[r] * 1e6

        # HYDROPOWER ROR
        HydroRoRGeneration[r in REGION, h in PERIOD],
            Electricity[r, :HydroRoR, h] <= ror_inflow[r, h] * time_step

        # PUMPED STORAGE HYDROPOWER
        PSopenBalance[r in REGION, h in PERIOD],
            PSopenLevel[r,h] <= PSopenLevel[r, h>1 ? h-1 : length(PERIOD)] +
            + Electricity[r,:PSHopenPump,h] * eta[:PSHopenPump] * eta[:PSHopenTurb] - Electricity[r,:PSHopenTurb,h] + PS_inflow[r,h] * time_step

        PSclosedBalance[r in REGION, h in PERIOD],
            PSclosedLevel[r,h] <= PSclosedLevel[r, h>1 ? h-1 : length(PERIOD)] +
            + Electricity[r,:PSHclosedPump,h] * eta[:PSHclosedPump] * eta[:PSHclosedTurb] - Electricity[r,:PSHclosedTurb,h]
        
        
        PowerBoundsPSHopenTurb[r in REGION, h in PERIOD],
            Electricity[r,:PSHopenTurb,h] <= Capacity_r[r, :PSHopenTurb] * time_step

        PowerBoundsPSHopenPump[r in REGION, h in PERIOD],
            Electricity[r,:PSHopenPump,h] <= Capacity_r[r, :PSHopenPump] * time_step

        PowerBoundsPSHclosedTurb[r in REGION, h in PERIOD],
            Electricity[r,:PSHclosedTurb,h] <= Capacity_r[r, :PSHclosedTurb] * time_step

        PowerBoundsPSHclosedPump[r in REGION, h in PERIOD],
            Electricity[r,:PSHclosedPump,h] <= Capacity_r[r, :PSHclosedPump] * time_step
        

        PSopenReservoirSize[r in REGION, h in PERIOD],
            PSopenLevel[r, h] <= PSopenReservoir[r] * 1e6     # [MWh]

        PSclosedReservoirSize[r in REGION, h in PERIOD],
            PSclosedLevel[r, h] <= PSclosedReservoir[r] * 1e6     # [MWh]

            
        MinPSopenReservoirLevel[r in REGION, h in PERIOD],
            PSopenLevel[r, h] >= min_reservoir_level[r] * PSopenReservoir[r] * 1e6

        # HYDROGEN
        PowerBoundsH2GT[r in REGION, h in PERIOD],
			Electricity[r,:H2GT,h] <= Capacity_r[r,:H2GT] * time_step

        PowerBoundsElectrolyzer[r in REGION, h in PERIOD],
            Electricity[r,:Electrolyzer,h] <= Capacity_r[r,:Electrolyzer] * time_step
        
        H2StorageSize[r in REGION, h in PERIOD],
            H2StorageLevel[r, h] <= Capacity_r[r, :H2Storage]

        H2StorageBalance[r in REGION, h in PERIOD],
            H2StorageLevel[r, h] == H2StorageLevel[r, h>1 ? h-1 : length(PERIOD)] +
            + Electricity[r,:Electrolyzer,h] * eta[:Electrolyzer] - Electricity[r, :H2GT, h] / eta[:H2GT]

        # SYSTEM ENERGY BALANCE
        ElecDemand[r in REGION, h in PERIOD],
            sum(Electricity[r, p, h] for p in PLANT) +
            - Electricity[r, :Battery, h] - Electricity[r, :PSHopenPump, h] - Electricity[r, :PSHclosedPump, h] - Electricity[r, :Electrolyzer, h] + 
            + Electricity[r, :Inverter, h] + Electricity[r, :PSHopenTurb, h] + Electricity[r, :PSHclosedTurb, h] + Electricity[r, :H2GT, h] +
            + sum((1- loss_per_K_Km)^(distance[r1, r] / 1000) * Transmission[r1, r, h] for r1 in REGION if valid_links[r1, r]) +
            - sum(Transmission[r, r1, h] for r1 in REGION if valid_links[r, r1]) >= load[r, h] * time_step - DemandResponse[r, h] - ENS[r, h]

        DemandResponseCap[r in REGION, h in PERIOD],
            DemandResponse[r, h] <= load[r, h] * time_step * demand_response_ratio

        SystemTotalEmissions,
            TotalEmissions == 8760 /(time_step * no_periods) * sum(Electricity[r, p, h]/eta[p]*emissionfactor[p] for r in REGION, p in TECH, h in PERIOD)

        # CARBON CAP
        CarbonCap,
		    TotalEmissions <= carbon_cap * 8760 /(time_step * no_periods) * sum(load[r, h] * time_step - DemandResponse[r, h] - ENS[r,h] for r in REGION, h in PERIOD)

        SystemOperationalCost,
            OperationalCost == 8760 /(time_step * no_periods) * (sum(Electricity[r, p, h]*(fuel_cost[p]/eta[p] + var_cost[p]) for r in REGION, p in TECH, h in PERIOD))

        SystemFixedCost,
            FixedCost == sum(Capacity_r[r, p]*fixed_cost[p] for r in REGION, p in TECH)

        SystemInvestmentCost,
            InvestmentCost == sum(Capacity_r[r, p]*inv_cost[p]*crf[p] for r in REGION, p in TECH) +
                           + sum(TransmissionCapacity_r[r, r1]*distance[r, r1] for r in REGION, r1 in REGION if r1 > r && valid_links[r, r1])*transmissioncost*crf_t
        SystemDemandResponse,
            TotalDemandResponseCost == demand_response_penalty * 8760 /(time_step * no_periods) * sum(DemandResponse[r, h] for r in REGION, h in PERIOD)

        # ENERGY NOT SERVED
        SystemTotalENSCost,
            TotalENSCost == VOLL * 8760 /(time_step * no_periods) * sum(ENS[r, h] for r in REGION, h in PERIOD)

    end #constraints

    @expression(m, TotalENS_per_region[r in REGION], 8760 /(time_step * no_periods) * sum(ENS[r, h] for h in PERIOD))
    @expression(m, TotalDemandResponse_per_region[r in REGION], 8760 /(time_step * no_periods) * sum(DemandResponse[r, h] for h in PERIOD))
    @expression(m, TotalDemand_per_region[r in REGION], 8760 /(time_step * no_periods) * sum(load[r, h] * time_step for h in PERIOD))

    @objective m Min begin
        InvestmentCost + OperationalCost + FixedCost + TotalDemandResponseCost + TotalENSCost 
    end
    return (;m, Electricity, TotalEmissions, OperationalCost, FixedCost, InvestmentCost, TotalDemandResponseCost, TotalENSCost, PlannedOutage, TotalENS_per_region, TotalDemand_per_region, TotalDemandResponse_per_region)
end 

