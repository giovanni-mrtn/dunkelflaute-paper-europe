"""
RunStochasticModel(problem, input, scenario_data)

Builds and solves the stochastic JuMP model (calls `Build_Stochastic_Model`), checks solver termination,
and returns a compact named tuple with objective, capacities, dispatch, and cost/emissions results.
"""
function RunStochasticModel(problem, input, scenario_data)
    @unpack REGION, PLANT,TECH, PERIOD, no_regions, no_plants, no_techs, no_periods, valid_links = input
    @unpack SCENARIO, load, cf, prob = scenario_data
    @unpack storage, transmission, nuclear, time_step, planned_outage_rate = problem
    model = Build_Stochastic_Model(problem, input, scenario_data)
    @unpack m, Capacity, Electricity, TransmissionCapacity, TotalEmissions, OperationalCost, InvestmentCost, FixedCost, TotalDemandResponseCost, PlannedOutage   = model
    println("\nSolving model...")
    optimize!(m)

    ts = termination_status(m)      # IF ERROR: comment out this line and the if block below
    if ts == MOI.OPTIMAL
        println("\nSolve status: Optimal")
        
    #elseif ts == MOI.TIME_LIMIT && has_values(m)
    #    println("\nSolve status: Reached the time-limit (feasible solution available)")
    
    elseif (ts == MOI.TIME_LIMIT || ts == MOI.MEMORY_LIMIT) && has_values(m)
        println("\nSolve status: Reached limit ($ts) (feasible solution available)")
    elseif ts == MOI.LOCALLY_SOLVED && has_values(m)
        # Gurobi barrier sometimes returns SUBOPTIMAL (mapped to LOCALLY_SOLVED) when convergence tolerances aren't fully met but a near-optimal feasible point exists.
        @warn "Solve status: LOCALLY_SOLVED — accepting near-optimal solution"
    else
        error("The model was not solved correctly: termination status = $(ts)")
    end

    Cost_r = objective_value(m)/1e6 
    Capacity_r = value.(Capacity)
    Electricity_r = value.(Electricity)
    TransmissionCapacity_r = value.(TransmissionCapacity)
    TotalEmissions_r = value.(TotalEmissions)
    TotalDemandResponseCost_r = value.(TotalDemandResponseCost)
    OperationalCost_r = value.(OperationalCost)
    FixedCost_r = value(FixedCost)
    InvestmentCost_r = value(InvestmentCost)
    PlannedOutage_r = value.(PlannedOutage) 

    # Free memory
    m = nothing

    return (; status = ts, Cost_r, Capacity_r, Electricity_r, TransmissionCapacity_r, TotalEmissions_r, TotalDemandResponseCost_r, OperationalCost_r, FixedCost_r, InvestmentCost_r, PlannedOutage_r)
end

